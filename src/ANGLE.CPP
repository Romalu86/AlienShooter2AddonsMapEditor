void ANGLE::InitializeYTables()
{
    const float scale = 0.7070602178573608f;
    for (int index=0; index<256; ++index)
    {
        SinYTable[index] = SinTable[index]*scale;
        CosYTable[index] = CosTable[index]*scale;
    }
}

VECTOR2 ANGLE::RotateY(const VECTOR2& vectorValue) const
{
    return VECTOR2(
        vectorValue.x*CosTable[value]-vectorValue.y*SinTable[value],
        vectorValue.x*SinYTable[value]+vectorValue.y*CosYTable[value]);
}

VECTOR2 VAbs(const VECTOR2& vectorValue)
{
    return VECTOR2(std::fabs(vectorValue.x), std::fabs(vectorValue.y));
}

